/** 開閉できる Q&A */
export default function Help() {
  const [open, setOpen] = useState<number>();
  return (
    <ScrollView contentContainerStyle={{ paddingVertical: 12, paddingBottom: 48, gap: 8 }}>
      {TOPICS.map((t, i) => (
        <View key={t.q} style={[s.card, { paddingVertical: 4 }]}>
          <Pressable
            onPress={() => (smooth(), setOpen(open === i ? undefined : i))}
            accessibilityRole="button"
            accessibilityState={{ expanded: open === i }}
            style={[s.row, { paddingVertical: 12 }]}>
            <Text style={[s.text, { flex: 1, fontWeight: '600' }]}>{t.q}</Text>
            <Text style={s.small}>{open === i ? '閉じる' : '開く'}</Text>
          </Pressable>
          {open === i && (
            <View style={[s.divider, { paddingTop: 12, paddingBottom: 10, gap: 10 }]}>
              <Text style={[s.text, { fontSize: 15, lineHeight: 23 }]}>{t.a}</Text>
              {t.to && (
                <Link href={t.to[1]} asChild>
                  <Pressable style={{ alignSelf: 'flex-start', paddingVertical: 4 }}>
                    <Text style={s.link}>{t.to[0]} ›</Text>
                  </Pressable>
                </Link>
              )}
            </View>
          )}
        </View>
      ))}
      <Text style={[s.small, { textAlign: 'center', marginTop: 8, color: C.sub }]}>ここに無いことは、「わたし」タブから設定を見直してみてください。</Text>
    </ScrollView>
  );
}
